import pandas as pd

df = pd.read_csv('/content/sales_data.csv')

print(df.shape)
print(df.columns.tolist())

# Count missing values in each column
print(df.isna().sum())

# Count fully duplicated rows
print("Duplicate rows:", df.duplicated().sum())

# No missing values or duplicates were found, so these lines change nothing.
# They are included to show the cleaning step was done.
df = df.dropna()
df = df.drop_duplicates()

print("Rows after cleaning:", len(df))

# Metric 1: total revenue across all sales
total_revenue = df['Total_Sales'].sum()
print("Total revenue:", total_revenue)

# Metric 2: best-selling product by revenue
revenue_by_product = df.groupby('Product')['Total_Sales'].sum().sort_values(ascending=False)
print("\nRevenue by product:")
print(revenue_by_product)
print("Best-selling product:", revenue_by_product.idxmax())

# Metric 3: average order value
avg_order_value = df['Total_Sales'].mean()
print("\nAverage order value:", round(avg_order_value, 2))

# Metric 4: revenue by region
revenue_by_region = df.groupby('Region')['Total_Sales'].sum().sort_values(ascending=False)
print("\nRevenue by region:")
print(revenue_by_region)
print("Top region:", revenue_by_region.idxmax())

report = f"""# Sales Data Analysis Report

## Data Overview
- Total rows: {len(df)}
- Total columns: {len(df.columns)}
- Missing values: none found
- Duplicate rows: none found

## Key Metrics
- Total revenue: {total_revenue:,}
- Average order value: {avg_order_value:,.2f}
- Best-selling product: {revenue_by_product.idxmax()} ({revenue_by_product.max():,})
- Top region: {revenue_by_region.idxmax()} ({revenue_by_region.max():,})

## Limitations
- Unit prices vary widely within each product, which is unusual for real products. This suggests synthetic data, so treat these results as practice, not business conclusions.
- Each customer appears in only one transaction, so repeat purchases cannot be analysed.
"""

with open('analysis_report.md', 'w') as f:
    f.write(report)

print("Report written.")

